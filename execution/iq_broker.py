"""
Persistent IQ Option connection for the long-running bot service.

Differences from execution/iqoption.py (the one-shot GitHub Actions client):

  * One connection for the life of the process, re-established automatically.
  * Results are matched to trades BY ORDER ID, from three sources in order:
      1. socket-option-closed push  (exact win/loss + amounts)
      2. listInfoData push          (exact win/loss, amount from payout)
      3. closed-options history     (last N closed options, searched by id)
    The old client relied on check_win_v3, which only ever looks at the single
    most recently closed option, then fell back to diffing the balance — both
    break as soon as two trades are open at once. Nothing here guesses: if no
    source reports the order, the caller eventually records UNKNOWN.
  * No OTC fallback by default. OTC prices are generated by IQ Option and are
    not the market the strategy reads from Deriv, so signals don't apply there.

Every library call is wrapped in a timeout because iqoptionapi busy-waits on
websocket replies. A call that never returns leaves a spinning thread behind;
after MAX_STUCK of those the process exits so Docker restarts it clean (open
trades are in SQLite and get reconciled from history on startup).
"""

import logging
import os
import threading
import time

logger = logging.getLogger(__name__)

CONNECT_TIMEOUT = 45
CALL_TIMEOUT    = 15
MAX_STUCK       = 3
CACHE_SECONDS   = 1800   # open-asset and payout catalog refresh
AUTH_BACKOFF    = 1800   # after IQ rejects the credentials — hammering a bad password risks a lockout
MAX_BACKOFF     = 300    # cap for other connect failures (10s, 20s, 40s ... 300s)


class CallTimeout(Exception):
    pass


class IQBroker:
    name = "IQ Option"

    @property
    def is_demo(self) -> bool:
        return self.demo

    def __init__(self, email: str, password: str, demo: bool = True, allow_otc: bool = False):
        self.email     = email
        self.password  = password
        self.demo      = demo
        self.allow_otc = allow_otc
        self.iq        = None
        self.balance   = 0.0
        self._stuck    = 0
        self._payouts: dict[str, float] = {}
        self._open: set[str] | None = None
        self._catalog_at = 0.0
        self._next_attempt = 0.0
        self._fail_streak = 0
        self.auth_rejected = False
        self.catalog: dict[str, set[str]] = {}   # option type -> tickers open right now
        self._listed: set[str] = set()           # every turbo/binary ticker IQ offers at all

    # ── Connection ────────────────────────────────────────────────────────

    def connected(self) -> bool:
        try:
            return self.iq is not None and bool(self.iq.check_connect())
        except Exception:
            return False

    def ensure_connected(self) -> bool:
        if self.connected():
            return True
        if time.time() < self._next_attempt:
            return False
        if self.iq is not None:
            logger.warning("IQ Option connection lost — reconnecting")
        if self._connect():
            self._fail_streak, self.auth_rejected = 0, False
            return True
        self._fail_streak += 1
        delay = AUTH_BACKOFF if self.auth_rejected else min(MAX_BACKOFF, 10 * 2 ** (self._fail_streak - 1))
        self._next_attempt = time.time() + delay
        logger.warning(f"Next IQ Option connect attempt in {delay}s")
        return False

    def _connect(self) -> bool:
        def _do():
            from iqoptionapi.stable_api import IQ_Option
            iq = IQ_Option(self.email, self.password)
            ok, reason = iq.connect()
            return iq, ok, reason

        try:
            iq, ok, reason = self._call(_do, CONNECT_TIMEOUT)
        except CallTimeout:
            logger.error(f"IQ Option connect timed out after {CONNECT_TIMEOUT}s")
            return False
        except Exception as e:
            logger.error(f"IQ Option connect error: {e}")
            return False
        if not ok:
            self.auth_rejected = "invalid_credentials" in str(reason)
            logger.error(f"IQ Option login failed: {reason}")
            return False

        self.iq = iq
        self.iq.change_balance("PRACTICE" if self.demo else "REAL")
        self.refresh_balance()
        self._catalog_at = 0.0
        logger.info(f"IQ Option connected ({'DEMO' if self.demo else 'LIVE'}) | Balance: USD {self.balance:.2f}")
        return True

    def close(self) -> None:
        try:
            if self.iq:
                self.iq.api.close()
        except Exception:
            pass

    # ── Account / catalog ─────────────────────────────────────────────────

    def refresh_balance(self) -> float:
        try:
            self.balance = float(self._call(self.iq.get_balance))
        except Exception as e:
            logger.warning(f"Balance read failed: {e}")
        return self.balance

    def ticker_for(self, base: str) -> tuple[str | None, str]:
        """Pick the tradeable ticker for a base symbol. Returns (ticker, reason)."""
        self._refresh_catalog()
        if self._open is None or base in self._open:
            return base, ""
        if self.allow_otc and f"{base}-OTC" in self._open:
            return f"{base}-OTC", ""
        if base not in self._listed:
            why = f"IQ Option offers no real-market turbo option for {base} (OTC only)"
        else:
            why = f"{base} turbo suspended on IQ Option right now"
        return None, why + ("" if self.allow_otc else "; OTC trading disabled")

    def availability(self, bases: list[str]) -> dict[str, str]:
        """Per base symbol, which IQ option types are open now, e.g. {'USDJPY': 'digital'}."""
        self._refresh_catalog()
        out = {}
        for base in bases:
            parts = []
            for tick in (base, f"{base}-OTC"):
                if tick not in self._listed:
                    parts.append(f"{tick}: not offered")
                    continue
                kinds = [k for k, syms in self.catalog.items() if tick in syms]
                pay = f" {self._payouts[tick]:.0%}" if tick in self._payouts else ""
                parts.append(f"{tick}: {'open ' + '/'.join(kinds) if kinds else 'suspended'}{pay}")
            out[base] = " | ".join(parts)
        return out

    def payout(self, ticker: str) -> float | None:
        self._refresh_catalog()
        return self._payouts.get(ticker)

    def _refresh_catalog(self) -> None:
        """
        Open turbo/binary assets and turbo payouts, from one get_all_init call.

        Not get_all_open_time / get_all_profit: the former also queries IQ's
        digital-options catalog, which no longer answers (30s hang, then a crash
        in a library thread), and every hang counted toward the stuck-call exit.
        """
        if time.time() - self._catalog_at < CACHE_SECONDS:
            return
        self._catalog_at = time.time()
        try:
            res = self._call(self.iq.get_all_init, 30)["result"]
            catalog: dict[str, set[str]] = {"turbo": set(), "binary": set()}
            payouts: dict[str, float] = {}
            listed: set[str] = set()
            for kind in catalog:
                for a in res[kind]["actives"].values():
                    name = str(a.get("name", "")).split(".", 1)[-1].upper()
                    listed.add(name)
                    if a.get("enabled") and not a.get("is_suspended"):
                        catalog[kind].add(name)
                    commission = (a.get("option") or {}).get("profit", {}).get("commission")
                    if kind == "turbo" and commission is not None:
                        payouts[name] = (100 - float(commission)) / 100
            self.catalog, self._payouts, self._listed = catalog, payouts, listed
            self._open = catalog["turbo"]
        except Exception as e:
            logger.warning(f"IQ asset catalog unavailable ({e!r}) — will try placements anyway")
            self._open = None

    # ── Orders ────────────────────────────────────────────────────────────

    def symbol_for(self, yf_symbol: str) -> str | None:
        import config
        return config.IQ_SYMBOLS.get(yf_symbol)

    def buy(self, ticker: str, direction: str, amount: float, minutes: int,
            min_payout: float = 0.0) -> tuple[dict | None, str]:
        """Place a turbo option. Returns ({order_id, expiry, payout, stake}, "") or (None, reason)."""
        from iqoptionapi.expiration import get_expiration_time
        payout = self.payout(ticker)
        if payout is not None and payout < min_payout:
            return None, f"payout {payout:.0%} < minimum {min_payout:.0%}"
        action = "call" if direction == "BUY" else "put"
        try:
            # Same expiry the library will request — computed first so we know it exactly.
            expiry, _ = get_expiration_time(int(self.iq.api.timesync.server_timestamp), minutes)
            ok, order_id = self._call(lambda: self.iq.buy(amount, ticker, action, minutes))
        except KeyError:
            return None, f"IQ Option has no asset code for {ticker}"
        except Exception as e:
            return None, f"IQ buy error: {e}"
        if not ok or order_id is None:
            return None, f"IQ Option rejected the order ({order_id})"
        return {"order_id": str(order_id), "expiry": int(expiry), "payout": payout, "stake": amount}, ""

    def pushed_result(self, order_id: str, stake: float, ticker: str) -> tuple[str, float | None, str] | None:
        """Non-blocking read of results IQ Option pushed over the websocket."""
        api = self.iq.api if self.iq else None
        if api is None:
            return None
        for key in (order_id, _as_int(order_id)):
            msg = api.socket_option_closed.get(key) if key is not None else None
            if msg:
                m = msg["msg"]
                return _status(m["win"]), _profit(m["win"], float(m.get("sum", stake)), m.get("win_amount")), "socket"
        try:
            info = api.listinfodata.get(_as_int(order_id))
        except Exception:
            info = None
        if info and info.get("game_state") == 1:
            win = info["win"]
            pay = self._payouts.get(ticker)
            amount = stake * (1 + pay) if (win == "win" and pay) else None
            return _status(win), _profit(win, stake, amount), "listinfo"
        return None

    def history_results(self, limit: int = 50) -> dict[str, tuple[str, float, str]]:
        """Recently closed options keyed by order id (fallback when pushes were missed)."""
        try:
            data = self._call(lambda: self.iq.get_optioninfo_v2(limit), 20)
        except Exception as e:
            logger.warning(f"Closed-options history unavailable: {e}")
            return {}
        out = {}
        for o in data.get("msg", {}).get("closed_options", []):
            ids = o.get("id") or []
            if not ids:
                continue
            win = o.get("win", "")
            if win not in ("win", "loose", "equal"):
                continue
            out[str(ids[0])] = (_status(win), _profit(win, float(o.get("amount", 0)), o.get("win_amount")), "history")
        return out

    # ── Internals ─────────────────────────────────────────────────────────

    def _call(self, fn, timeout: float = CALL_TIMEOUT):
        box: dict = {}

        def run():
            try:
                box["value"] = fn()
            except Exception as e:
                box["error"] = e

        t = threading.Thread(target=run, daemon=True)
        t.start()
        t.join(timeout)
        if t.is_alive():
            self._stuck += 1
            logger.error(f"IQ Option call timed out ({self._stuck}/{MAX_STUCK} stuck threads)")
            if self._stuck >= MAX_STUCK:
                logger.critical("Too many stuck IQ Option calls — exiting for a clean restart")
                logging.shutdown()
                os._exit(3)
            raise CallTimeout()
        if "error" in box:
            raise box["error"]
        return box.get("value")


def _as_int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return None


def _status(win: str) -> str:
    return {"win": "WIN", "loose": "LOSS", "equal": "TIE"}.get(win, "UNKNOWN")


def _profit(win: str, stake: float, win_amount) -> float | None:
    if win == "loose":
        return -stake
    if win == "equal":
        return 0.0
    if win == "win" and win_amount is not None:
        return round(float(win_amount) - stake, 2)
    return None
